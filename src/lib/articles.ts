export function article(slug: string): Article | undefined {
  return ARTICLES.find((item) => item.slug === slug);
}

/** Articles that link to a feature or salon type page, for its "read more" list. */
export function articlesFor(seoSlug: string): Article[] {
  return ARTICLES.filter((item) => item.related.includes(seoSlug));
}

/** Rough reading time in minutes: Georgian words are long, so about 150 a minute, rounded up. */
export function readingMinutes(item: Article): number {
  const text = [item.lead, ...item.sections.flatMap((section) => [section.heading, ...(section.paragraphs ?? []), ...(section.list ?? []), ...(section.after ?? [])])].join(" ");
  return Math.max(1, Math.ceil(text.split(/\s+/).filter(Boolean).length / 150));
}
